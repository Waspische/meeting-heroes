// Lightweight, zero-dependency i18n module for Meeting Heroes
// Supports all ADEO countries & languages: FR, EN, ES, PT, PT-BR, IT, PL, UK, RO

export type SupportedLang = 'fr' | 'en' | 'es' | 'pt' | 'pt-BR' | 'it' | 'pl' | 'uk' | 'ro';

export const getLanguage = (): SupportedLang => {
  const stored = (typeof localStorage !== 'undefined' && typeof localStorage.getItem === 'function')
    ? localStorage.getItem('optimeeting_lang') as SupportedLang
    : null;
  if (stored && translations[stored]) return stored;

  const browserLang = ((typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage?.()) ||
    (typeof navigator !== 'undefined' && navigator.language) || 'fr').toLowerCase();

  if (browserLang.startsWith('pt-br')) return 'pt-BR';
  if (browserLang.startsWith('pt')) return 'pt';
  if (browserLang.startsWith('es')) return 'es';
  if (browserLang.startsWith('it')) return 'it';
  if (browserLang.startsWith('pl')) return 'pl';
  if (browserLang.startsWith('uk')) return 'uk';
  if (browserLang.startsWith('ro')) return 'ro';
  if (browserLang.startsWith('fr')) return 'fr';
  if (browserLang.startsWith('en')) return 'en';

  return 'en';
};

export const setLanguage = (lang: SupportedLang) => {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('optimeeting_lang', lang);
  }
};

